// Fast sine lookup (angle in degrees)
static inline int16_t fast_sin_deg(uint16_t angle) {
    return sin_table[angle % 360];
}

// Fast cosine using same table
static inline int16_t fast_cos_deg(uint16_t angle) {
    return sin_table[(angle + 90) % 360];
}

// Multiply integer by sine, rounding to nearest integer
int24_t fast_sin_mul(int16_t value, uint16_t angle) {
    int24_t s = fast_sin_deg(angle);
    int24_t product = value * s;
    if (product >= 0)
        return (product + (FP_SCALE / 2)) >> 8;
    else
        return (product - (FP_SCALE / 2)) >> 8;
}

// Multiply integer by cosine, rounding to nearest integer
int24_t fast_cos_mul(int24_t value, uint16_t angle) {
    int24_t c = fast_cos_deg(angle);
    int24_t product = value * c;
    if (product >= 0)
        return (product + (FP_SCALE / 2)) >> 8;
    else
        return (product - (FP_SCALE / 2)) >> 8;
}

